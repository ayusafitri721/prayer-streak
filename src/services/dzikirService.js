function normalizeSession(value) {
  return String(value || "").toLowerCase() === "petang" ? "petang" : "pagi";
}

function getRawListBySession(session) {
  return normalizeSession(session) === "petang" ? EVENING_DZIKIR : MORNING_DZIKIR;
}

function withOrder(items) {
  return items.map((item, index) => ({
    ...item,
    ...(DZIKIR_TEXT_BY_TITLE[item.title] || {}),
    order: index + 1,
    repeatLabel: `${item.repeatCount}x`,
  }));
}

function toSafeIndex(value, max) {
  const numericValue = Number.parseInt(value, 10);
  if (!Number.isFinite(numericValue) || numericValue < 0) return 0;
  if (numericValue >= max) return Math.max(0, max - 1);
  return numericValue;
}

